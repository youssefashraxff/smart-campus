-- Owned by booking-engine.
CREATE TABLE bookings (
    id            INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id       INT          NOT NULL,
    facility_id   INT          NOT NULL,
    start_time    TIMESTAMPTZ  NOT NULL,
    end_time      TIMESTAMPTZ  NOT NULL,
    status        VARCHAR(20)  NOT NULL CHECK (status IN ('Confirmed','Cancelled')),
    created_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CHECK (end_time > start_time)
);

CREATE TABLE registrations (
    id            INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id       INT          NOT NULL,
    event_id      INT          NOT NULL,
    status        VARCHAR(20)  NOT NULL CHECK (status IN ('Registered','Cancelled')),
    created_at    TIMESTAMPTZ  NOT NULL DEFAULT now()
);
-- one active registration per user per event
CREATE UNIQUE INDEX ux_registrations_active
    ON registrations (user_id, event_id) WHERE status = 'Registered';

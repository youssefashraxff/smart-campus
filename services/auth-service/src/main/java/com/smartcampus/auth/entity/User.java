package com.smartcampus.auth.entity;

import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.EnumType;
import jakarta.persistence.Enumerated;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.PrePersist;
import jakarta.persistence.Table;
import java.time.OffsetDateTime;
import lombok.Getter;

// Maps the users table (V1__create_users.sql). Column names come from Hibernate's default
// naming: field universityId -> column university_id.
@Getter
@Entity
@Table(name = "users")
public class User {

    // The database generates the id (INT GENERATED BY DEFAULT AS IDENTITY)
    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    private Integer id;

    @Column(nullable = false, length = 120)
    private String name;

    @Column(nullable = false, length = 20, unique = true)
    private String universityId;

    @Column(nullable = false, length = 160, unique = true)
    private String email;

    // BCrypt hash, never the plain password (NFR-5)
    @Column(nullable = false, length = 100)
    private String passwordHash;

    @Enumerated(EnumType.STRING)
    private Role role;

    private OffsetDateTime createdAt;

    // Runs just before the first INSERT, so every new row gets a creation time
    @PrePersist
    void onCreate() {
        if (createdAt == null) {
            createdAt = OffsetDateTime.now();
        }
    }
}
